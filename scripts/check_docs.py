"""Check repository Markdown/HTML links without a network or site build.

Generated NumPy/FP16 assets are intentionally absent from source control. Their
documented locations are accepted; all authored pages, images and anchors must
exist. Historical evidence locators in YAML/JSON are immutable source records,
not navigational links.
"""

from __future__ import annotations

import re
import sys
from html.parser import HTMLParser
from pathlib import Path
from urllib.parse import unquote, urlsplit

ROOT = Path(__file__).resolve().parents[1]
EXCLUDED = {".git", ".venv", "venv", "build", "dist", "node_modules", "vendor"}


class Links(HTMLParser):
    """Collect HTML links, asset references and explicit anchor IDs."""

    def __init__(self) -> None:
        super().__init__()
        self.targets: list[str] = []
        self.anchors: set[str] = set()

    def handle_starttag(self, tag: str, attrs: list[tuple[str, str | None]]) -> None:
        for name, value in attrs:
            if value is not None and name in {"href", "src"}:
                self.targets.append(value)
            if value is not None and name == "id":
                self.anchors.add(value)


def markdown_prose(text: str) -> str:
    """Remove fenced examples before interpreting Markdown links/headings."""
    return re.sub(r"(?ms)^(```|~~~).*?^\1[^\n]*$", "", text)


def anchors(path: Path) -> set[str]:
    text = path.read_text(encoding="utf-8")
    parser = Links()
    parser.feed(text)
    found = parser.anchors
    if path.suffix == ".md":
        counts: dict[str, int] = {}
        for title in re.findall(r"(?m)^#{1,6}\s+(.+?)\s*#*\s*$", markdown_prose(text)):
            slug = re.sub(r"[^\w\- ]", "", title.lower()).replace(" ", "-")
            number = counts.get(slug, 0)
            found.add(f"{slug}-{number}" if number else slug)
            counts[slug] = number + 1
    return found


def check() -> list[str]:
    errors = []
    anchor_cache: dict[Path, set[str]] = {}
    for source in sorted(ROOT.rglob("*")):
        if source.suffix not in {".md", ".html"} or EXCLUDED.intersection(source.parts):
            continue
        text = source.read_text(encoding="utf-8")
        if source.suffix == ".md":
            text = markdown_prose(text)
        parser = Links()
        parser.feed(text)
        targets = parser.targets
        if source.suffix == ".md":
            targets += re.findall(r"!?\[[^\]\n]*\]\(<?([^\s)>]+)>?(?:\s+[^)]*)?\)", text)
            targets += re.findall(r"(?m)^\s*\[[^\]]+\]:\s*<?([^\s>]+)>?", text)
        for target in targets:
            url = urlsplit(target)
            if url.scheme or url.netloc or target.startswith("//"):
                continue
            destination = (source.parent / unquote(url.path)).resolve() if url.path else source
            if destination.is_dir():
                for index in ("index.html", "README.md"):
                    if (destination / index).exists():
                        destination = destination / index
                        break
            # These precise generated formats are regenerated by the documented CLI.
            relative = destination.relative_to(ROOT) if destination.is_relative_to(ROOT) else None
            if (
                relative
                and destination.suffix in {".npy", ".npz", ".f16"}
                and relative.parts[0] in {"reports", "web"}
            ):
                continue
            if not destination.exists():
                errors.append(f"{source.relative_to(ROOT)}: missing {target}")
            elif url.fragment and destination.suffix in {".md", ".html"}:
                if destination not in anchor_cache:
                    anchor_cache[destination] = anchors(destination)
                if unquote(url.fragment) not in anchor_cache[destination]:
                    errors.append(f"{source.relative_to(ROOT)}: unknown anchor {target}")
    return errors


def main() -> int:
    errors = check()
    if errors:
        print("\n".join(errors))
        print(f"Documentation links: {len(errors)} error(s)")
        return 1
    print("Documentation links: all local targets and anchors passed")
    return 0


if __name__ == "__main__":
    sys.exit(main())
